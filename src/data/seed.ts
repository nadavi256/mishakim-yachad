function approved(activityId: string, userIds: string[], iso: string): Participation[] {
  return userIds.map((user_id, i) => ({
    id: `p-${activityId}-${i}`,
    activity_id: activityId,
    user_id,
    status: "approved" as const,
    approved_at: iso,
  }));
}

function anons(prefix: string, count: number): string[] {
  return Array.from({ length: count }, (_, i) => `${prefix}-${i + 1}`);
}

